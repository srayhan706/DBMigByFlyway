CREATE TABLE categories (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    CONSTRAINT uk_categories_name UNIQUE (name)
);

-- Reference data travels with the schema, so every environment gets the same rows.
INSERT INTO categories (name)
VALUES ('Peripherals'),
       ('Displays'),
       ('Audio');

-- Nullable, so the products that already exist stay valid without a category.
ALTER TABLE products
    ADD COLUMN category_id BIGINT,
    ADD CONSTRAINT fk_products_category FOREIGN KEY (category_id) REFERENCES categories (id);

-- Postgres does not index foreign key columns automatically.
CREATE INDEX idx_products_category_id ON products (category_id);
